import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { describe, it } from 'node:test';

const source = readFileSync(new URL('./RoutePlannerPreview.tsx', import.meta.url), 'utf8');
const workspaceSource = readFileSync(new URL('./QuoteItineraryWorkspace.tsx', import.meta.url), 'utf8');
const presetsSource = readFileSync(new URL('./day-route-presets.ts', import.meta.url), 'utf8');
const narrativeSource = readFileSync(new URL('./day-narrative-preview.ts', import.meta.url), 'utf8');

function expectSourceContains(src: string, fragments: string[]) {
  for (const fragment of fragments) {
    assert.ok(src.includes(fragment), `Expected source to contain: ${fragment}`);
  }
}

describe('Phase S.2D-2 — Route Planner "Apply to Day" (existing day PATCH only)', () => {
  it('renders one row per day with a preset dropdown reusing DAY_ROUTE_PRESETS', () => {
    expectSourceContains(source, [
      'export function RoutePlannerPreview',
      "import { DAY_ROUTE_PRESETS, getDayRoutePreset, getClassicJordanRouteTemplate } from './day-route-presets'",
      'aria-label="Route Planner"',
      'sorted.map((day) =>',
      'Day {String(day.dayNumber).padStart(2, \'0\')}',
      'Current title:',
      'DAY_ROUTE_PRESETS.map((p) =>',
      '<option key={p.key} value={p.key}>{p.label}</option>',
      'Custom / keep current',
      'Leisure / no transport',
      'preset.defaultTitle',
      'preset.narrative',
      'preset.overnightCity',
    ]);
  });

  it('Apply to Day writes ONLY title + notes via the existing PATCH /itinerary/day/:dayId', () => {
    expectSourceContains(source, [
      // explicit, destructive-action button copy
      'Replace Day with Selected Preset',
      // apply handler hits the EXISTING day PATCH endpoint (no new endpoint)
      'async function applyPresetToDay',
      "method: 'PATCH'",
      '`${apiBaseUrl}/itinerary/day/${day.id}`',
      // payload is ONLY the title + client-safe narrative
      'body: JSON.stringify({ title: preset.defaultTitle, notes: preset.narrative })',
      // reuse the standard auth + error helpers + refresh
      'buildAuthHeaders',
      'getErrorMessage',
      'router.refresh()',
      // confirmation before overwriting the day
      'This will replace the current day title and narrative with the selected route preset. Continue?',
    ]);
    // The PATCH body must NOT touch dayNumber / sortOrder / isActive (partial
    // update). Scope the check to JSON.stringify(...) so the header comment that
    // describes the partial update doesn't false-positive.
    assert.ok(!/JSON\.stringify\([^)]*sortOrder/.test(source), 'apply body must not send sortOrder');
    assert.ok(!/JSON\.stringify\([^)]*isActive/.test(source), 'apply body must not send isActive');
    assert.ok(!/JSON\.stringify\([^)]*dayNumber/.test(source), 'apply body must not send dayNumber');
  });

  it('Custom / keep current and Leisure never PATCH; no items / generator / pricing', () => {
    // applyPresetToDay bails when there is no real preset (Custom-keep / Leisure).
    expectSourceContains(source, ['const preset = getDayRoutePreset(presetKey);', 'if (!preset) return;']);
    // No QuoteItem creation, no generator/apply call.
    assert.ok(!/['"`][^'"`]*\/items['"`]/.test(source), 'must not create QuoteItems');
    assert.ok(!source.includes('tailor-made-draft'), 'must not call the generator/apply endpoints');
    // No mutation of the passed-in day objects.
    assert.ok(!/day\.title\s*=/.test(source), 'must not mutate day.title');
    assert.ok(!/day\.narrative\s*=/.test(source), 'must not mutate day narrative');
  });

  it('S.2D-3B/-3C: Classic Jordan Route Template preview + Apply (4/5/6/7-day) via day PATCH', () => {
    expectSourceContains(source, [
      // reuses the merged template constants (no new data)
      "import { DAY_ROUTE_PRESETS, getDayRoutePreset, getClassicJordanRouteTemplate } from './day-route-presets'",
      'const templateKeys = getClassicJordanRouteTemplate(sorted.length)',
      'aria-label="Classic Jordan Route Template"',
      'Classic Jordan Route Template',
      // one preview row per template day with title + overnight + narrative
      'templateKeys.map((key, index) =>',
      'tp?.defaultTitle',
      "tp?.overnightCity ?? 'No overnight (departure day)'",
      'tp?.narrative',
      // 4-day + 5-day warnings (approved copy)
      '4-day classic is a short highlights program. It skips Wadi Rum and gives Petra limited time.',
      '5-day classic is a faster-paced program. It skips Jerash to keep Wadi Rum and Dead Sea.',
      // 8-day → existing-generator note; other durations → basic-shell note
      'The 8-day classic route is currently generated by the existing structured generator.',
      'No curated classic template exists yet. Use the basic shell and edit days manually.',
      // S.2D-3C — Apply Template handler: loops the existing day PATCH (title + notes only)
      'async function applyTemplate',
      'for (let i = 0; i < templateKeys.length; i++)',
      '`${apiBaseUrl}/itinerary/day/${day.id}`',
      "method: 'PATCH'",
      'body: JSON.stringify({ title: tp.defaultTitle, notes: tp.narrative })',
      'router.refresh()',
      // strong confirmation before overwriting multiple days
      'This will replace the current day titles and narratives with the selected Classic Jordan route template. Services and pricing will not be changed. Continue?',
      // day-count guard
      'This template requires ${templateKeys.length} itinerary days. Please create or adjust the itinerary days first.',
      // the Apply button is wired (enabled for templated durations) — only rendered inside the templateKeys branch
      'onClick={applyTemplate}',
      'disabled={applyingTemplate}',
    ]);
    // The template PATCH body must carry ONLY title + notes (scope the field checks
    // to JSON.stringify so the descriptive header comment doesn't false-positive).
    assert.ok(!/JSON\.stringify\([^)]*sortOrder/.test(source), 'template apply body must not send sortOrder');
    assert.ok(!/JSON\.stringify\([^)]*isActive/.test(source), 'template apply body must not send isActive');
    assert.ok(!/JSON\.stringify\([^)]*dayNumber/.test(source), 'template apply body must not send dayNumber');
    // No QuoteItems / generator from the whole component.
    assert.ok(!/['"`][^'"`]*\/items['"`]/.test(source), 'must not create QuoteItems');
    assert.ok(!source.includes('tailor-made-draft'), 'must not call the generator/apply endpoints');
    // The disabled-placeholder + outdated copy are gone (apply is real now).
    assert.ok(!source.includes('Template apply comes in the next phase.'), 'disabled placeholder removed');
    assert.ok(!source.includes('Preview only — templates are not saved yet.'), 'preview-only template copy removed');
    assert.ok(!source.includes('requires a curated departure preset before automation'), 'old 5-day warning removed');
  });

  it('is mounted in the itinerary workspace with apiBaseUrl + day ids', () => {
    expectSourceContains(workspaceSource, [
      "import { RoutePlannerPreview } from './RoutePlannerPreview';",
      '<RoutePlannerPreview',
      'apiBaseUrl={apiBaseUrl}',
      // R.7A-1/-2 — day notes + applied services are forwarded to the preview.
      'days={quoteItinerary.days.map((day) => ({ id: day.id, dayNumber: day.dayNumber, title: day.title, notes: day.notes, appliedServices: toRoutePlannerAppliedServices(day.dayItems) }))}',
      'id="qb-route-planner"',
    ]);
  });

  it('maps applied QuoteItems to client-safe service descriptors (R.7A-2)', () => {
    expectSourceContains(workspaceSource, [
      'function toRoutePlannerAppliedServices',
      "{ kind: 'guide' as const }",
      "{ kind: 'hotel' as const }",
      "{ kind: 'transport' as const }",
      // R.7A-2.1 — activity prefers the linked Activity public name (service is null for activities)
      "{ kind: 'activity' as const, name: qs.activityName ?? qs.service?.name ?? null }",
      "{ kind: 'entrance' as const, name: qs.service?.name ?? null }",
    ]);
    // The mapper must NOT forward pricing/supplier/contract/room/meal fields.
    assert.ok(!/appliedVehicleRate\.vehicle|qs\.contract|qs\.roomCategory|pricingDescription|sellPrice|markupPercent/.test(workspaceSource.split('toRoutePlannerAppliedServices')[1]?.slice(0, 600) || ''), 'mapper forwards no pricing/supplier/room fields');
  });

  it('the preset catalog it reuses is unchanged (no new places exposed here)', () => {
    expectSourceContains(presetsSource, ['export const DAY_ROUTE_PRESETS', 'export const CUSTOM_DAY_PRESET_KEY']);
  });
});

describe('Phase R.7A-1 — read-only client narrative preview (route/day text only)', () => {
  it('10/11. renders a "Client narrative preview" per day with the "not saved yet" label', () => {
    expectSourceContains(source, [
      // reuses the pure helper (no network)
      "import { buildDayNarrativePreview, type AppliedNarrativeService } from './day-narrative-preview'",
      'buildDayNarrativePreview({',
      'title: day.title',
      'notes: day.notes',
      // the read-only block + copy
      'aria-label="Client narrative preview"',
      'Client narrative preview',
      'narrativePreview.text',
      'Preview only — not saved yet',
    ]);
    // The preview is read-only — no <button> wraps the narrative, and there is no
    // "Use this narrative" save action in R.7A-1/-2.
    assert.ok(!source.includes('Use this narrative'), 'no save action');
    assert.ok(!source.includes('Save narrative') && !source.includes('Apply narrative'), 'no save/apply narrative action');
  });

  it('R.7A-2: forwards applied services + shows "Includes applied services" only when service-aware', () => {
    expectSourceContains(source, [
      // helper import now also pulls the applied-service type
      "import { buildDayNarrativePreview, type AppliedNarrativeService } from './day-narrative-preview'",
      // applied services threaded into the preview helper
      'appliedServices: day.appliedServices',
      // conditional label, only when the preview actually wove services in
      "narrativePreview.sourceLayer === 'service-aware'",
      'Includes applied services',
    ]);
  });

  it('12/13/14/15. the preview adds no write/network/proposal/pricing coupling', () => {
    // No suggestion endpoints called from the component (route/day text only).
    assert.ok(!source.includes('tailor-made-draft'), 'preview must not call suggestion/generator endpoints');
    // No new PATCH/POST/DELETE introduced by the narrative preview. The only
    // network calls remain the pre-existing day PATCH apply handlers (S.2D-2/-3C).
    const patchCount = (source.match(/method:\s*['"]PATCH['"]/g) || []).length;
    assert.equal(patchCount, 2, 'exactly the two pre-existing day-PATCH apply handlers remain');
    assert.ok(!/method:\s*['"](POST|DELETE)['"]/.test(source), 'no POST/DELETE added');
    // The pure helper itself performs no I/O (call-shaped checks, so its own
    // descriptive header comment — "NO PATCH", "NO proposal-v3 change" — doesn't
    // false-positive).
    assert.ok(!/fetch\s*\(/.test(narrativeSource), 'helper makes no network calls');
    assert.ok(!/useRouter|router\.\w+\(/.test(narrativeSource), 'helper does not navigate/refresh');
    assert.ok(!/method:\s*['"]/.test(narrativeSource), 'helper issues no HTTP method');
  });
});
